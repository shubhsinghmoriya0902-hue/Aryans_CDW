def match_tech_field_courses(text: str) -> list:
    """Returns list of matched tech-field courses from the compiled docx catalogue."""
    low = text.lower()
    matched = []
    for course in TECH_FIELD_COURSES:
        c_low = course.lower()
        if len(c_low) <= 4:
            if re.search(r"\b" + re.escape(c_low) + r"\b", low):
                matched.append(course)
        else:
            if c_low in low:
                matched.append(course)
    return matched
